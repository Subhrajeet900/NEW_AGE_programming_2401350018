(println "=== 1. LIST ===")
(def my-list (list 1 2 3 4))
(println "Original list:" my-list)
(println "first:" (first my-list))
(println "rest:" (rest my-list))
(def new-list (conj my-list 0))
(println "New list after conj:" new-list)
(println "Original list unchanged:" my-list)

(println "\n=== 2. VECTOR ===")
(def my-vector [10 20 30 40])
(println "Original vector:" my-vector)
(println "get index 2:" (get my-vector 2))
(println "count:" (count my-vector))
(def new-vector (conj my-vector 50))
(println "New vector after conj:" new-vector)
(println "Original vector unchanged:" my-vector)

(println "\n=== 3. MAP ===")
(def my-map {:name "Subhrajeet" :age 20 :course "CSE"})
(println "Original map:" my-map)
(println "get :name:" (get my-map :name))
(def map-after-assoc (assoc my-map :city "hyderabad"))
(println "New map after assoc:" map-after-assoc)
(println "Original map unchanged:" my-map)
(def map-after-dissoc (dissoc my-map :age))
(println "New map after dissoc:" map-after-dissoc)
(println "Original map unchanged:" my-map)

(println "\n=== 4. SET ===")
(def my-set #{1 2 3 4})
(println "Original set:" my-set)
(println "contains? 3:" (contains? my-set 3))
(def set-after-conj (conj my-set 5))
(println "New set after conj:" set-after-conj)
(println "Original set unchanged:" my-set)
(def set-after-disj (disj my-set 2))
(println "New set after disj:" set-after-disj)
(println "Original set unchanged:" my-set)

