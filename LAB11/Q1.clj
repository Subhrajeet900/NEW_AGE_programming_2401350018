(println "=== 1. Java Static Methods ===")
(def abs-val (Math/abs -25))
(def sqrt-val (Math/sqrt 144.0))
(def current-time (System/currentTimeMillis))
(println "Math/abs of -25:" abs-val)
(println "Math/sqrt of 144.0:" sqrt-val)
(println "System/currentTimeMillis:" current-time)

(println "\n=== 2 & 3. Create Java Objects and Invoke Instance Methods ===")
(def student-list (new java.util.ArrayList))
(.add student-list "Subhrajeet")
(.add student-list "Deep")
(.add student-list "Harsh")
(println "ArrayList:" student-list)
(println "ArrayList size:" (.size student-list))
(println "Element at index 0:" (.get student-list 0))

(def student-map (java.util.HashMap.))
(.put student-map "name" "Subhrajeet")
(.put student-map "roll" "2401350018")
(.put student-map "course" "Computer Science")
(println "\nHashMap:" student-map)
(println "Get 'name' from HashMap:" (.get student-map "name"))
(println "HashMap size:" (.size student-map))

(println "\n=== 4. Convert Between Clojure and Java Collections ===")
(def clojure-vec (vec student-list))
(println "Java ArrayList converted to Clojure Vector:" clojure-vec)
(println "Type:" (type clojure-vec))

(def clojure-map (into {} student-map))
(println "Java HashMap converted to Clojure Map:" clojure-map)
(println "Type:" (type clojure-map))

(def clj-data ["Subhrajeet" "Deep" "Harsh"])
(def java-list-from-clj (java.util.ArrayList. clj-data))
(println "\nClojure Vector converted to Java ArrayList:" java-list-from-clj)
(println "Type:" (type java-list-from-clj))

(def clj-map-data {"name" "Subhrajeet" "roll" "2401350018"})
(def java-map-from-clj (java.util.HashMap. clj-map-data))
(println "Clojure Map converted to Java HashMap:" java-map-from-clj)
(println "Type:" (type java-map-from-clj))

